// Builds src/data/india-map.ts: one simplified SVG path of India as depicted by the Natural Earth "India point of view" dataset
// (ne_10m_admin_0_countries_ind, public domain), which follows the boundary as recognised by the Government of India.
// Source: https://github.com/nvkelso/natural-earth-vector (download raw-media/_geo/ne10_ind.geojson first; see docs/ASSETS.md).
import fs from "node:fs";
const g = JSON.parse(fs.readFileSync("raw-media/_geo/ne10_ind.geojson", "utf8"));
const f = g.features.find((x) => x.properties.ISO_A3 === "IND" || x.properties.ADM0_A3 === "IND" || x.properties.ADMIN === "India");
const polys = f.geometry.type === "MultiPolygon" ? f.geometry.coordinates : [f.geometry.coordinates];

const lon0 = 82.5, lat0 = 22; // central meridian and parallel for the (slightly conic-flattened) projection
const k = Math.cos((lat0 * Math.PI) / 180);
const proj = ([lon, lat]) => [(lon - lon0) * k, -lat];
const area = (r) => Math.abs(r.reduce((s, p, i) => { const q = r[(i + 1) % r.length]; return s + p[0] * q[1] - q[0] * p[1]; }, 0) / 2);

function dp(pts, eps) { // Douglas-Peucker
  if (pts.length < 3) return pts;
  let max = 0, idx = 0; const [a, b] = [pts[0], pts[pts.length - 1]];
  const dx = b[0] - a[0], dy = b[1] - a[1], len = Math.hypot(dx, dy) || 1e-9;
  for (let i = 1; i < pts.length - 1; i++) { const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + b[0] * a[1] - b[1] * a[0]) / len; if (d > max) { max = d; idx = i; } }
  if (max <= eps) return [a, b];
  return [...dp(pts.slice(0, idx + 1), eps).slice(0, -1), ...dp(pts.slice(idx), eps)];
}
const rings = polys.map((p) => p[0].map(proj)).filter((r) => area(r) > 0.01).map((r) => { const m = r.length >> 1; return [...dp(r.slice(0, m + 1), 0.025).slice(0, -1), ...dp(r.slice(m), 0.025)]; }) // closed ring: split so DP has two distinct end points
  .filter((r) => r.length > 3);
const all = rings.flat();
const minX = Math.min(...all.map((p) => p[0])), maxX = Math.max(...all.map((p) => p[0]));
const minY = Math.min(...all.map((p) => p[1])), maxY = Math.max(...all.map((p) => p[1]));
const S = 1000 / (maxX - minX); // width 1000 units
const W = 1000, H = Math.round((maxY - minY) * S);
const pt = (p) => [(p[0] - minX) * S, (p[1] - minY) * S];
const d = rings.map((r) => "M" + r.map((p) => pt(p).map((v) => v.toFixed(1)).join(" ")).join("L") + "Z").join("");
const wr = pt(proj([79.53, 17.98])); // Warangal
const out = `// Generated by scripts/build-india-map.mjs from Natural Earth (public domain), India point-of-view boundaries. Do not edit.
// The faculty coordinator must review this depiction (docs/COPY-REVIEW.md).
export const indiaMap = {
  viewBox: "0 0 ${W} ${H}", width: ${W}, height: ${H},
  path: ${JSON.stringify(d)},
  /** Projection used for pins: same maths as the build script. */
  project: { lon0: ${lon0}, k: ${k.toFixed(5)}, minX: ${minX.toFixed(5)}, minY: ${minY.toFixed(5)}, scale: ${S.toFixed(5)} },
} as const;
export const projectLatLon = (lat: number, lon: number): [number, number] => {
  const p = indiaMap.project;
  return [((lon - p.lon0) * p.k - p.minX) * p.scale, (-lat - p.minY) * p.scale];
};
`;
fs.writeFileSync("src/data/india-map.ts", out);
console.log(rings.length, "rings,", (out.length / 1024).toFixed(1), "KB, warangal", wr.map((v) => v.toFixed(1)), "view", W, H);
